/*
 * Download product-specific catalogue photos from Pixabay.
 * Run from frontend:
 *   $env:PIXABAY_KEY="your_key"; npm run images
 *   npm run images -- --dry
 * Options: --dry, --force, --only=<category-slug>
 *
 * Photos are written to public/images/products/<product-id>.jpg.
 * The manifest is updated after each successful download, so runs can resume.
 * Review downloaded matches before publishing: search results are not guaranteed
 * to be an exact match for every product.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ADDITIONAL_PRODUCTS } from "../src/data/additionalProducts.js";
import { PRODUCT_PHOTOS } from "../src/data/productImages.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDir = path.join(root, "public/images/products");
const manifestPath = path.join(root, "src/data/productImages.js");
const args = process.argv.slice(2);
const dryRun = args.includes("--dry");
const force = args.includes("--force");
const only = args.find((arg) => arg.startsWith("--only="))?.split("=")[1];
const apiKey = process.env.PIXABAY_KEY;

if (!dryRun && !apiKey) {
  console.error('Missing PIXABAY_KEY. In PowerShell: $env:PIXABAY_KEY="your_key"; npm run images');
  process.exit(1);
}

const hints = {
  "groceries-and-staples": "indian grocery product",
  "snacks-and-beverages": "food product",
  "dairy-and-bakery": "dairy bakery food",
  "fruits-and-vegetables": "fresh produce",
  "household-and-cleaning": "cleaning product",
  "kitchen-and-dining": "kitchen utensil",
  "personal-care": "personal care product",
  "electronics-and-accessories": "electronic accessory",
  "mens-fashion": "men clothing",
  "womens-fashion": "women clothing",
  "kids-and-baby": "baby kids product",
  "stationery-and-office": "stationery",
  "home-decor-and-furnishing": "home decor",
  "health-and-wellness": "health wellness product",
  "pet-and-garden": "pet garden product",
  "tools-and-hardware": "hardware tool",
  "auto-and-travel": "automotive travel product",
  "gifts-and-festival": "gift product",
};
const overrides = {
  "Curd": "yogurt curd in bowl",
  "Poha (Flattened Rice)": "flattened rice poha",
  "Rava (Semolina)": "semolina",
  "Besan": "gram flour chickpea flour",
  "Kumkum": "kumkum powder",
  "Rangoli Colours": "rangoli powder",
  "Dhoti": "traditional dhoti clothing",
  "Lungi": "lungi cloth",
  "Cycle": "bicycle",
  "Diya Set": "clay diya lamps",
};
const clean = (value) => value.replace(/\(.*?\)/g, "").replace(/\s+/g, " ").trim();
const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function saveManifest(photos) {
  const sorted = Object.fromEntries(Object.entries(photos).sort(([a], [b]) => a.localeCompare(b)));
  fs.writeFileSync(
    manifestPath,
    "// Generated by npm run images. Maps sample product IDs to local photo files.\n" +
    `export const PRODUCT_PHOTOS = ${JSON.stringify(sorted, null, 2)};\n`
  );
}

async function findPhoto(query) {
  const url = new URL("https://pixabay.com/api/");
  url.search = new URLSearchParams({
    key: apiKey, q: query, image_type: "photo", safesearch: "true",
    per_page: "5", order: "popular",
  });
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Pixabay API returned HTTP ${response.status}`);
  const payload = await response.json();
  return payload.hits?.[0] || null;
}

async function download(url, destination) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Image download returned HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (!bytes.length) throw new Error("Downloaded image was empty");
  fs.writeFileSync(destination, bytes);
}

fs.mkdirSync(outputDir, { recursive: true });
const photos = { ...PRODUCT_PHOTOS };
const products = ADDITIONAL_PRODUCTS.filter((product) => !only || product.category.includes(only));
const missing = [];
console.log(`Checking ${products.length} catalogue products${dryRun ? " (dry run)" : ""}.`);

for (const product of products) {
  const filename = `${product.id}.jpg`;
  const destination = path.join(outputDir, filename);
  const query = overrides[product.name] || `${clean(product.name)} ${hints[product.category] || "product"}`;
  if (dryRun) {
    console.log(`${product.id} -> ${query}`);
    continue;
  }
  if (!force && photos[product.id] && fs.existsSync(destination)) continue;
  try {
    const hit = await findPhoto(query);
    if (!hit?.webformatURL) {
      missing.push(product.name);
      console.log(`No photo found: ${product.name}`);
    } else {
      await download(hit.webformatURL, destination);
      photos[product.id] = filename;
      saveManifest(photos);
      console.log(`Downloaded: ${product.name}`);
    }
  } catch (error) {
    missing.push(product.name);
    console.log(`Skipped ${product.name}: ${error.message}`);
  }
  await wait(700);
}

if (!dryRun) {
  saveManifest(photos);
  console.log(`Finished. ${Object.keys(photos).length} photos are in the manifest.`);
  if (missing.length) console.log(`No photo downloaded for ${missing.length} products: ${missing.join(", ")}`);
  console.log("Review every photo/product match before deploying.");
}
